/**
 * Грубая эвристика токсичности без вызова LLM (как в «Мой Лендинг»).
 * Лёгкая критика и скепсис закупки («дорого», «сомневаемся», «докажите») не режем — отрабатывает модель по системному промпту.
 */

const ABUSIVE_SUBSTRINGS = [
  "хуй",
  "хуя",
  "хуе",
  "хуи",
  "хуё",
  "пизд",
  "ебан",
  "ёбан",
  "ебал",
  "ебу",
  "ебёт",
  "ебет",
  "бляд",
  "блять",
  "сука",
  "мудак",
  "мудач",
  "говно",
  "говен",
  "shit",
  "fuck",
] as const;

export function isLikelyAbusiveUserText(text: string): boolean {
  const t = text.toLowerCase().replace(/ё/g, "е");
  return ABUSIVE_SUBSTRINGS.some((w) => t.includes(w));
}

