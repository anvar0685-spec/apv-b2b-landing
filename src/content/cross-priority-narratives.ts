export function getPriorityCrossNarrative(professionSlug: string, citySlug: string): string[] | null {
  if (!isPriorityCross(professionSlug, citySlug)) return null;
  const prof = getProfession(professionSlug);
  const city = getCity(citySlug);
  if (!prof || !city) return null;
  const p = BY_PRO[professionSlug];
  const c = BY_CITY[citySlug];
  const b = BRIDGE[`${professionSlug}:${citySlug}`];
  if (!p || !c) return null;
  if (b) return [...p, ...c, ...b];
  return [...p, ...c, `Локальный вывод «${prof.titleRu}» в ${city.nameRu}. Уточните объект и пик в заявке — подготовим КП с тем же объёмом работ, что в сравнении площадок.`];
}

/** Локальный нарратив для любой пары «профессия × город»: приоритетные 30 — расширенный текст; остальные — профиль + город + CTA. */
export function getProgrammaticLocalNarrative(professionSlug: string, citySlug: string): string[] {
  const priority = getPriorityCrossNarrative(professionSlug, citySlug);
  if (priority?.length) return priority;

  const prof = getProfession(professionSlug);
  const city = getCity(citySlug);
  if (!prof || !city) return [];

  const pro = BY_PRO[professionSlug] ?? defaultProParagraphs(prof.titleRu);
  const cityParas = getCityLocalParagraphs(citySlug, city.nameRu);
  const closing = [
    `Для «${prof.titleRu}» в ${city.nameRu} следующий шаг — калькулятор на сайте и заявка: менеджер подготовит КП с резервом, коэффициентами ночи и выходных и форматом отчёта по сменам под ваш объект.`,
  ];
  return [...pro, ...cityParas, ...closing];
}

