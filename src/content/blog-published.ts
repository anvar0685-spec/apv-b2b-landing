export function getBlogArticle(slug: string): BlogArticle | undefined {
  return PUBLISHED_BLOG_ARTICLES.find((a) => a.slug === slug);
}

export function relatedArticles(slug: string, category: string, limit = 5): BlogArticle[] {
  const other = PUBLISHED_BLOG_ARTICLES.filter((a) => a.slug !== slug);
  const same = other.filter((a) => a.category === category);
  const rest = other.filter((a) => a.category !== category);
  return [...same, ...rest].slice(0, limit);
}
