import { getWarehouseHourlyRateRub } from "@/content/warehouse-hourly-rates";

type Prof = { slug: string; titleRu: string; titleGenitiveRu: string };
type City = { slug: string; nameRu: string; namePrepositionalRu: string };

/**
 * Развёрнутое тело для каждой пары «профессия × город».
 *
 * @param priority — для приоритетных 30 пар (см. `cross-priority.ts`) возвращаем полный
 * каркас (13 абзацев) с уникальными вставками из `cross-priority-narratives`.
 * Для остальных пар — компактный каркас (5 абзацев): закупочный минимум + ставка + переход
 * к калькулятору. Длинная стена текста на «тонкой» странице — главный риск «doorway»-фильтра.
 */
export function getProgrammaticLongreadParagraphs(profession: Prof, city: City, priority = false): string[] {
  const { slug: pSlug, titleGenitiveRu: roleGenitive } = profession;
  const { slug: cSlug, namePrepositionalRu: cityPrepositional } = city;
  const rate = getWarehouseHourlyRateRub(pSlug);
  const isMoscow = cSlug === "moskva";
  const locHint = isMoscow
    ? "Внутри МКАД и по округам Москвы критичны согласованные окна у ворот, время подхода бригады и резерв на замену в «час пик» логистики."
    : "В Московской области выход на объект привязан к транспортным коридорам и плотности складских кластеров рядом с трассами и терминалами.";

  if (!priority) {
    return [
      `Закрываем складские смены с ${roleGenitive} в ${cityPrepositional}: подрядчик отвечает за явку, замены и отчётность, заказчик — за процесс и показатели линии. Аутстаффинг не оказываем.`,
      `Ориентир почасовой ставки — от ${rate} ₽/ч (день, базовый сценарий Москва/МО). Ночь, сутки, пики маркетплейсов и усиленные требования площадки удорожают смену; итог фиксируется в КП после диагностики объекта.`,
      locHint,
      `Калькулятор даёт ориентир по месячному фонду с учётом численности, графика и надбавок. После заявки менеджер подготовит КП для ${roleGenitive} в ${cityPrepositional}: резерв, коэффициенты ночи и выходных, формат отчётности.`,
      `Соседние города можно сравнить в разделе «Персонал». Гарантии, штрафы и порядок приёмки фиксируем только в договоре и приложениях.`,
    ];
  }

  return [
    `Закрываем складские смены с ${roleGenitive} в ${cityPrepositional}: подрядчик отвечает за явку, замены и отчётность, заказчик — за процесс и показатели линии.`,
    `Ориентир почасовой ставки на сайте — от ${rate} ₽/ч (день, базовый сценарий Москва/МО). Ночь, сутки, пики маркетплейсов и усиленные требования площадки удорожают смену; итоговый фонд и гарантии фиксируются в КП и договоре после обсуждения объекта.`,
    locHint,
    `Закупке и дирекции склада нужны одни и те же данные: явка, закрытие смены, выработка линии, ошибки, инциденты и время замены. Отчётность настраиваем под ваш рабочий ритм — ежесменно, раз в неделю или по событиям.`,
    "Аутстаффинг не оказываем. Закрытие смен оформляем договором; инструктажи, медосмотры и документы на допуск ведём в согласованном объёме со стороны подрядчика.",
    `Для ${roleGenitive} чаще всего важны приёмка и отгрузка, комплектация, отбор или кросс-док. Резерв считаем под конкретную зону: скорость перемещений, документы, допуски и потребность в постоянном составе.`,
    `Старт с части зоны или части смен снижает риск при смене подрядчика или расширении площади. Первые смены — разбор узких мест, ввод людей в регламент, обратная связь от бригадиров; объём наращиваем после стабилизации, без резкого скачка численности в первый день.`,
    `Оформление, документы на допуск, пропускной режим и медосмотры согласовываем заранее. Службу безопасности заказчика не заменяем, но передаём полный пакет документов под проверку.`,
    `Калькулятор даёт ориентир по месячному фонду с учётом численности, графика и надбавок. Параметры переходят в заявку, поэтому менеджеру не придётся повторно собирать исходные данные.`,
    "Схема работы и примеры объектов — в разделах «Услуги» и «Кейсы». Другие города Московской области можно сравнить в разделе «Персонал», отраслевые особенности — в разделе «Отрасли».",
    `Если у вас яркая сезонность (новый год, распродажи, промо маркетплейсов), в КП закладываем пики: запас бригад, удлинённые смены, ночные окна и правило «когда звонить ночью» при просадке явки — чтобы линия не встала из‑за случайной неявки.`,
    `Штрафы, бонусы, порядок приёмки и форс-мажор фиксируем только в договоре и приложениях. На странице указаны ориентиры, а не индивидуальные обязательства.`,
    `Чтобы получить расчёт для ${roleGenitive} в ${cityPrepositional}, укажите объект и график в заявке. Менеджер подготовит КП с разложением ставок, резерва и отчётности.`,
  ];
}
